export const DEFAULT_LANG: Lang = "vi";

/** One language's full string table. */
export type Dict = Record<I18nKey, string>;

/**
 * Only the default language ships in the initial bundle. The other languages
 * are code-split and fetched by `loadDict` when the user switches, so a
 * visitor no longer downloads all three string tables up front.
 */
export { default as DEFAULT_DICT } from './dict.vi';

export async function loadDict(lang: Lang): Promise<Dict> {
  switch (lang) {
    case 'en':
      return (await import('./dict.en')).default;
    case 'ko':
      return (await import('./dict.ko')).default;
    default:
      return (await import('./dict.vi')).default;
  }
}
